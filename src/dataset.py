"""
dataset.py — Data loading and SUBJECT-WISE splitting.

Directly answers Reviewer 3 (Comment 1, Comment 3) and Reviewer 2 (data
leakage concern): every split in this codebase is generated by
`GroupKFold` / `GroupShuffleSplit` keyed on `subject_id`, never on image
index. A scan from subject S can therefore never appear in both the
training and test partition of the same fold.

Expected directory layout (edit `data.root_dir` in config.yaml to match
your local ADNI export):

    data/ADNI/
        NonDemented/S0001_scan01.png
        NonDemented/S0001_scan02.png
        VeryMildDemented/S0002_scan01.png
        ...

The filename prefix before the first underscore is treated as the
`subject_id`. Adjust `extract_subject_id` below if your ADNI export uses a
different naming convention (e.g. DICOM SubjectID metadata) — this is the
single choke point that determines leakage-safety, so keep it explicit
and auditable.
"""
from dataclasses import dataclass
from pathlib import Path
from typing import List

import numpy as np
from sklearn.model_selection import GroupKFold, GroupShuffleSplit


@dataclass
class Sample:
    path: str
    label: int
    subject_id: str


def extract_subject_id(filename: str) -> str:
    """Subject ID = the token before the first underscore in the filename.

    Example: 'S0001_scan01.png' -> 'S0001'.
    This is the ONLY place subject identity is derived from a filename;
    change it here (and only here) if your dataset's naming differs.
    """
    stem = Path(filename).stem
    return stem.split("_")[0]


def load_dataset_index(root_dir: str, classes: List[str]) -> List[Sample]:
    """Walk `root_dir/<class>/*` and build the full sample index.

    Raises a clear error rather than silently returning an empty/partial
    dataset, since a quietly-empty class is exactly the kind of issue
    Reviewer 3 flagged as needing a transparent, auditable dataset table.
    """
    samples: List[Sample] = []
    root = Path(root_dir)
    for label_idx, class_name in enumerate(classes):
        class_dir = root / class_name
        if not class_dir.is_dir():
            raise FileNotFoundError(
                f"Expected class directory not found: {class_dir}. "
                f"Check `data.root_dir` / `data.classes` in config.yaml."
            )
        files = sorted(
            [p for p in class_dir.iterdir() if p.suffix.lower() in (".png", ".jpg", ".jpeg")]
        )
        if not files:
            raise ValueError(f"No images found in {class_dir}.")
        for p in files:
            samples.append(
                Sample(path=str(p), label=label_idx, subject_id=extract_subject_id(p.name))
            )
    return samples


def subject_wise_kfold(samples: List[Sample], n_folds: int, seed: int):
    """Yield (train_idx, test_idx) index arrays with disjoint subject sets.

    Uses GroupKFold, which guarantees each subject_id is confined to a
    single fold. This is what Comment 3 (data-leakage risk) requires and
    is the ONLY splitting function used by train.py / ablation.py.
    """
    groups = np.array([s.subject_id for s in samples])
    X = np.arange(len(samples))
    gkf = GroupKFold(n_splits=n_folds)
    for train_idx, test_idx in gkf.split(X, groups=groups):
        # Sanity assertion — fail loudly if leakage is ever introduced.
        train_subjects = set(groups[train_idx])
        test_subjects = set(groups[test_idx])
        assert train_subjects.isdisjoint(test_subjects), (
            "Subject-wise split invariant violated: a subject appears in "
            "both train and test partitions of the same fold."
        )
        yield train_idx, test_idx


def subject_wise_holdout(samples: List[Sample], test_ratio: float, seed: int):
    """Single 80:20 subject-wise train/test split (used only for the quick
    sanity-check pipeline in scripts/run_all.py's `--quick` mode)."""
    groups = np.array([s.subject_id for s in samples])
    X = np.arange(len(samples))
    gss = GroupShuffleSplit(n_splits=1, test_size=test_ratio, random_state=seed)
    train_idx, test_idx = next(gss.split(X, groups=groups))
    assert set(groups[train_idx]).isdisjoint(set(groups[test_idx]))
    return train_idx, test_idx
